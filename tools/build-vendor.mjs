// Bundles third-party browser libraries that, unlike Muya, bundle cleanly: FullCalendar and
// force-graph become one ES module each in site/vendor. Also copies the self-hosted fonts to
// site/fonts (the app must not depend on Google Fonts: offline PWA, and headless test browsers
// here hang on external font requests).
import { cpSync, mkdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { build } from "esbuild";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const vendor = join(root, "site", "vendor");
rmSync(vendor, { recursive: true, force: true });
mkdirSync(vendor, { recursive: true });

const entries = {
  // One module exporting everything the calendar view needs, Estonian locale included.
  fullcalendar: `
    export { Calendar } from "@fullcalendar/core";
    export { default as dayGridPlugin } from "@fullcalendar/daygrid";
    export { default as timeGridPlugin } from "@fullcalendar/timegrid";
    export { default as listPlugin } from "@fullcalendar/list";
    export { default as interactionPlugin } from "@fullcalendar/interaction";
    export { default as etLocale } from "@fullcalendar/core/locales/et";
  `,
  "force-graph": `export { default } from "force-graph";`,
};
for (const [name, contents] of Object.entries(entries)) {
  await build({
    stdin: { contents, resolveDir: root, loader: "js" },
    bundle: true,
    format: "esm",
    minify: true,
    legalComments: "none",
    outfile: join(vendor, `${name}.js`),
  });
}

const fonts = join(root, "site", "fonts");
rmSync(fonts, { recursive: true, force: true });
mkdirSync(fonts, { recursive: true });
const faces = [
  ["Schibsted Grotesk", "schibsted-grotesk", "schibsted-grotesk-%s-wght-normal.woff2", "400 900", "normal"],
  ["Source Serif 4", "source-serif-4", "source-serif-4-%s-opsz-normal.woff2", "200 900", "normal"],
  ["Source Serif 4", "source-serif-4", "source-serif-4-%s-opsz-italic.woff2", "200 900", "italic"],
];
// latin-ext carries õ, š, ž; latin the rest. Same ranges as the fontsource CSS.
const ranges = {
  latin: "U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,U+0308,U+0329,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD",
  "latin-ext": "U+0100-02BA,U+02BD-02C5,U+02C7-02CC,U+02CE-02D7,U+02DD-02FF,U+0304,U+0308,U+0329,U+1D00-1DBF,U+1E00-1E9F,U+1EF2-1EFF,U+2020,U+20A0-20AB,U+20AD-20C0,U+2113,U+2C60-2C7F,U+A720-A7FF",
};
let css = "/* Generated by tools/build-vendor.mjs from @fontsource-variable packages (OFL). */\n";
for (const [family, pkg, pattern, weight, style] of faces) {
  for (const [subset, range] of Object.entries(ranges)) {
    const file = pattern.replace("%s", subset);
    cpSync(join(root, "node_modules", "@fontsource-variable", pkg, "files", file), join(fonts, file));
    css += `@font-face{font-family:"${family}";font-style:${style};font-display:swap;font-weight:${weight};src:url(/static/fonts/${file}) format("woff2");unicode-range:${range}}\n`;
  }
}
writeFileSync(join(fonts, "fonts.css"), css);
console.log("site/vendor and site/fonts built");
